"use client";

import { useEffect, useRef, useState } from "react";
import { Activity, Briefcase, Database, Search, Shield } from "lucide-react";
import { api, type AgentMessage, type Consensus, type DiscussionEvent } from "@/lib/api";
import { LevelBadge, Modal, Spinner } from "@/components/ui";

const AGENT_ICONS: Record<string, React.ReactElement> = {
  analyst: <Shield className="w-4 h-4" />,
  intel: <Search className="w-4 h-4" />,
  forensics: <Database className="w-4 h-4" />,
  business: <Briefcase className="w-4 h-4" />,
  response: <Activity className="w-4 h-4" />,
};

/** Streams a real multi-agent analysis of a risk or incident as the agents respond. */
export default function AgentDiscussionModal({
  riskId,
  incidentId,
  title,
  onClose,
  onFinished,
}: {
  riskId?: string;
  incidentId?: string;
  title: string;
  onClose: () => void;
  onFinished?: () => void;
}) {
  const [messages, setMessages] = useState<AgentMessage[]>([]);
  const [typing, setTyping] = useState<string[]>([]);
  const [consensus, setConsensus] = useState<Consensus | null>(null);
  const [meta, setMeta] = useState<{ mode: string; generated_by: string } | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [done, setDone] = useState(false);
  const bottom = useRef<HTMLDivElement>(null);

  useEffect(() => {
    const ctrl = new AbortController();
    api.agents
      .stream({ risk_id: riskId, incident_id: incidentId }, (e: DiscussionEvent) => {
        if (e.type === "started") setMeta({ mode: e.mode, generated_by: e.generated_by });
        else if (e.type === "typing") setTyping(e.agents);
        else if (e.type === "message") {
          setMessages((m) => [...m, e.message]);
          setTyping((t) => t.filter((a) => a !== e.message.agent));
        } else if (e.type === "consensus") setConsensus(e.consensus);
        else if (e.type === "done") {
          setDone(true);
          setTyping([]);
          onFinished?.();
        } else if (e.type === "error") {
          setError(e.message);
          setTyping([]);
        }
      }, ctrl.signal)
      .catch((err) => {
        if ((err as Error).name !== "AbortError") setError(err instanceof Error ? err.message : "Analysis failed");
      });
    return () => ctrl.abort();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [riskId, incidentId]);

  useEffect(() => {
    bottom.current?.scrollIntoView({ behavior: "smooth" });
  }, [messages, typing, consensus]);

  return (
    <Modal
      wide
      onClose={onClose}
      title={
        <span>
          AI Agent Analysis <span className="text-sm font-normal text-gray-500 dark:text-gray-300">— {title}</span>
        </span>
      }
    >
      {meta && (
        <p className="text-xs text-gray-500 dark:text-gray-300 mb-3">
          {meta.mode === "ai" ? `Generated by ${meta.generated_by}` : "Rules-engine mode (set GEMINI_API_KEY for LLM analysis)"} · grounded in live evidence
        </p>
      )}
      <div className="space-y-3">
        {messages.length === 0 && !error && <Spinner label="Agents are reviewing the evidence…" />}
        {messages.map((m) => (
          <div key={m.agent} className="p-3 rounded-md border border-gray-200 dark:border-gray-700">
            <div className="flex items-center justify-between mb-1">
              <span className="flex items-center gap-2 font-semibold text-sm text-gray-900 dark:text-white">
                {AGENT_ICONS[m.agent]} {m.name}
              </span>
              <span className="flex items-center gap-2">
                <LevelBadge level={m.severity} />
                <span className="text-xs text-gray-500 dark:text-gray-300">{m.confidence}% confident</span>
              </span>
            </div>
            <p className="text-sm text-gray-800 dark:text-gray-100 whitespace-pre-wrap">{m.message}</p>
            {m.recommendations.length > 0 && (
              <ul className="mt-2 list-disc list-inside text-xs text-gray-600 dark:text-gray-300 space-y-0.5">
                {m.recommendations.map((r, i) => (
                  <li key={i}>{r}</li>
                ))}
              </ul>
            )}
            {m.degraded && <p className="text-xs text-warning mt-1">Fell back to rules engine: {m.degraded}</p>}
          </div>
        ))}
        {typing.length > 0 && !error && (
          <p className="text-xs text-gray-500 dark:text-gray-300 animate-pulse">{typing.join(", ")} typing…</p>
        )}
        {consensus && (
          <div className="p-4 rounded-md bg-blue-50 dark:bg-gray-900 border border-blue-200 dark:border-gray-600">
            <div className="flex items-center justify-between mb-2">
              <h3 className="font-semibold text-gray-900 dark:text-white">Consensus</h3>
              <span className="flex items-center gap-2">
                <LevelBadge level={consensus.consensus_severity} />
                <span className="text-xs text-gray-600 dark:text-gray-300">
                  {consensus.confidence_score}% · agreement {consensus.agent_agreement.level}
                </span>
              </span>
            </div>
            <p className="text-sm text-gray-800 dark:text-gray-100 whitespace-pre-wrap">{consensus.executive_summary}</p>
            {consensus.prioritized_recommendations.length > 0 && (
              <ol className="mt-3 list-decimal list-inside text-sm text-gray-700 dark:text-gray-200 space-y-0.5">
                {consensus.prioritized_recommendations.slice(0, 6).map((r) => (
                  <li key={r.priority}>{r.recommendation}</li>
                ))}
              </ol>
            )}
            {consensus.escalation_required && <p className="mt-2 text-sm font-semibold text-critical">Escalation recommended</p>}
          </div>
        )}
        {error && (
          <p role="alert" className="text-sm text-critical">
            {error}
          </p>
        )}
        {done && <p className="text-xs text-success">Analysis complete and recorded in the audit ledger.</p>}
        <div ref={bottom} />
      </div>
    </Modal>
  );
}
